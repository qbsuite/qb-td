let named = null; // name -> text, built on first use
function lookup(name) {
  if (!named) {
    named = new Map();
    for (const group of TABLE.replace(/\n/g, '').split(',')) {
      const [names, hex] = group.split(':');
      const text = String.fromCodePoint(...hex.split('.').map((h) => parseInt(h, 16)));
      for (const n of names.split(' ')) named.set(n, text);
    }
  }
  return named.get(name);
}

function codePoint(n) {
  if ((n >= 0xd800 && n <= 0xdfff) || n > 0x10ffff) return '\ufffd';
  return String.fromCodePoint(n in NUMERIC ? NUMERIC[n] : n);
}

/**
 * `text` with its character references decoded, exactly as he.decode
 * does. `mark`, when given, is applied to what each reference decodes to
 * (questionWords marks the brackets a reference spelled out).
 */
export function decodeEntities(text, mark = (s) => s) {
  text = String(text ?? '');
  if (!text.includes('&')) return text;
  return text.replace(/&(?:#(\d+);?|#[xX]([\da-fA-F]+);?|([\da-zA-Z]+)(;?))/g, (all, dec, hex, name, semi) => {
    if (dec || hex) return mark(codePoint(parseInt(dec || hex, dec ? 10 : 16)));
    const whole = semi && lookup(name);
    if (whole) return mark(whole);
    const legacy = LEGACY.exec(name);
    return legacy ? mark(lookup(legacy[0])) + name.slice(legacy[0].length) + semi : all;
  });
}
